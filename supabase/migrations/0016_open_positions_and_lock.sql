-- 미청산 거래를 목록에 올리고, 차트 메모에 잠금을 단다.
--
-- 지금까지 동기화는 **닫힌** 포지션만 가져왔다. 들고 있는 동안에는 목록에 아무것도 없어
-- 진입 근거를 적어 둘 자리가 없었고, 청산되고 나서야 뒤늦게 떠올려 적어야 했다. 복기의
-- 절반은 "들어갈 때 무슨 생각이었나"인데 그 절반이 통째로 비어 있었던 셈이다.
--
-- 미청산 거래도 같은 `trades` 행으로 만든다. 청산되면 그 행을 **덮어써서** 닫는다 —
-- 새 행을 만들면 적어 둔 근거·복기·원칙 판단·차트 메모가 열려 있던 행에 남아 끊긴다.

-- 아직 안 닫힌 포지션이 지금까지 계좌에 남긴 순손익(미실현 + 이미 확정된 비용).
--
-- `pnl`·`realized_pnl`과 칸을 나눈 이유: 이 값은 확정된 것이 아니라 시세를 따라 계속
-- 움직인다. 같은 칸에 담으면 누적 손익·승률·기대치가 시세에 흔들리고, 잔고 대조에서는
-- 스냅샷의 미청산분과 이중으로 잡힌다. 청산될 때 null로 지운다.
alter table public.trades
  add column unrealized_pnl numeric;

comment on column public.trades.unrealized_pnl is
  '미청산 포지션의 평가손익. 청산되면 null이 되고 realized_pnl로 옮겨간다.';

-- 잠금 — 자리를 다 잡은 메모가 차트를 만지다 밀리지 않게 한다.
--
-- 잠긴 메모는 집히지 않는다. 그래야 그 위에서도 차트를 그대로 밀고 확대할 수 있다.
-- 푸는 자리는 차트 아래 메모 목록이다.
alter table public.trade_annotations
  add column locked boolean not null default false;
