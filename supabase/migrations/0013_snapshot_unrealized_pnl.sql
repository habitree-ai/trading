-- 잔고 스냅샷에 미청산 포지션의 손익을 함께 남긴다 — 계산 자금과 대조할 때 걷어내려고.
--
-- `equity`(OKX totalEq)에는 아직 안 닫힌 포지션이 남긴 금액이 이미 들어 있다. 반면
-- 계산 자금은 청산이 끝난 거래만 더한다. 둘을 그대로 견주면 포지션을 들고 있는 내내
-- 그 차이만큼 벌어져 보이고, 화면은 "놓친 거래나 입출금이 있습니다"라고 잘못 말한다 —
-- 분 단위로 매매하는 계좌는 거의 항상 포지션이 열려 있으므로 사실상 상시 오경보다.
--
-- 담는 값은 미실현 가격손익(`upl`)에 그 포지션이 이미 확정한 금액(`realizedPnl` —
-- 수수료·펀딩비·부분청산)을 더한 것이다. 미실현분만 빼면 이미 낸 수수료가 그대로 남아
-- 여전히 어긋난다. 포지션이 닫히는 날 이 값이 그 거래의 실현손익으로 들어와 상쇄된다.
alter table public.balance_snapshots
  add column unrealized_pnl numeric;

comment on column public.balance_snapshots.unrealized_pnl is
  '스냅샷 시점 미청산 포지션이 잔고에 남긴 순손익(미실현 가격손익 + 이미 확정된 수수료·펀딩비). equity 에 이미 포함돼 있다. 예전 스냅샷이면 null.';
